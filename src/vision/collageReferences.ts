// Fixed slots preserve the reference composition regardless of selected photo count.
export type CollageReference = {
  id: string;
  label: string;
  canvas: { width: number; height: number };
  frames: number[][];
  source?: number;
  color?: string;
  flowers?: boolean;
  accuracy: 'source' | 'screenshot';
};
const recipe = (
  number: number,
  label: string,
  width: number,
  height: number,
  frames: number[][],
  extra: Partial<CollageReference> = {},
): CollageReference => ({
  id:
    number === 1
      ? 'collage-mosaic'
      : number === 2
        ? 'collage-columns'
        : number === 3
          ? 'collage-layered'
          : `collage-reference-${number}`,
  label,
  canvas: { width, height },
  frames,
  accuracy: number <= 10 || number === 18 ? 'source' : 'screenshot',
  ...extra,
});
